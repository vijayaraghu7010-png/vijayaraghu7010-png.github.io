lines.push('');
lines.push(`insert into themes (name, kind, tokens, is_default, is_active)
  select 'WrappedStudio', 'base', ${j(base)}, true, true
  where not exists (select 1 from themes where is_default);`);

festivals.forEach((f) => {
  lines.push(`insert into themes (name, kind, tokens, is_active, banner_text)
  select ${q(f.name)}, 'festival', ${j(f.tokens)}, false, ${q(f.banner)}
  where not exists (select 1 from themes where name = ${q(f.name)});`);
});

