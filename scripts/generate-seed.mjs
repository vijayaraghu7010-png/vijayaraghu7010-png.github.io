/* Builds supabase/migrations/0002_seed.sql from the data files the
   site shipped with, so the database starts out holding exactly what
   is on the site today. Re-runnable: every statement is an upsert. */
import { writeFileSync } from 'node:fs';
import { PRODUCTS } from '../src/data/products.js';
import { BRAND, CONTACT, BENEFITS, CATEGORIES } from '../src/data/categories.js';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `'${JSON.stringify(v ?? []).replace(/'/g, "''")}'::jsonb`;
const n = (v) => (v === null || v === undefined || v === '' ? 'null' : Number(v));

const lines = ['-- generated by scripts/generate-seed.mjs - do not edit by hand', ''];

PRODUCTS.forEach((p, i) => {
  lines.push(`insert into products (
  id, slug, name, category, category_label, price, price_mode, unit_label, unit_noun,
  min_qty, set_size, image, alt, gallery, short_description, description, details,
  occasions, keywords, customiser, size_id, featured, sort_order, added_at
) values (
  ${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${q(p.categoryLabel)}, ${n(p.price)},
  ${q(p.priceMode)}, ${q(p.unitLabel || '')}, ${q(p.unitNoun || '')}, ${n(p.minQty)}, ${n(p.setSize)},
  ${q(p.image)}, ${q(p.alt)}, ${j(p.gallery)}, ${q(p.shortDescription)}, ${q(p.description)},
  ${j(p.details)}, ${j(p.occasions)}, ${j(p.keywords)}, ${q(p.customiser)}, ${q(p.sizeId)},
  ${p.featured ? 'true' : 'false'}, ${i}, ${q(p.addedAt)}
) on conflict (id) do nothing;`);
});

