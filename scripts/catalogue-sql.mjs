/* Turns the catalogue the site is built with into SQL.

   The server prices every order itself; it cannot take the browser's
   word for what a thing costs. That means the database needs the same
   catalogue the shop shows, and this writes the statements that put it
   there:

   - products: every row in src/data/products.js
   - price_variants: the things that are sold at a price but are not
     products in their own right - the three frame sizes, the twelve
     hamper boxes. The cart builds ids like
     `frame-couple-eye-frame-a4` for these, and the server has to be
     able to price one without trusting the number attached to it.

   Anything in the database that the catalogue no longer has is not
   deleted. It is marked unpublished, which takes it out of the shop and
   stops it being orderable while leaving the record alone.

   Run:  node --import ./tests/resolve-extensions.mjs scripts/catalogue-sql.mjs
   It prints SQL. It does not connect to anything.                    */

import { PRODUCTS, FRAME_SIZES, POSTER_SIZES } from '../src/data/products.js';
import { BOX_VARIANTS } from '../src/data/hamperKit.js';

const q = (v) =>
  v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;

/* Money is held as whole paise everywhere past the browser. */
const paise = (rupees) => Math.round(Number(rupees) * 100);

const lines = [];

lines.push('-- generated by scripts/catalogue-sql.mjs - do not edit by hand');
lines.push('begin;');

// ------------------------------------------------------------ products

/* The whole product, not just what it costs.

   This used to write only the columns the server prices from, on the
   reasoning that the shop had its own copy of everything else. It
   does not any more: the shop reads what the panel writes, so a row
   that carries no picture and no description is a product with no
   picture and no description. Seeding half a product left the
   catalogue showing seven posters with empty images.

   `published` is deliberately NOT overwritten on conflict. Something
   the studio has taken out of the shop must stay out when the
   catalogue is seeded again; only the sweep below, which names every
   id the bundle still has, decides that. */
const jsonb = (v) => `${q(JSON.stringify(Array.isArray(v) ? v : []))}::jsonb`;

const COLUMNS = [
  'id', 'slug', 'name', 'category', 'category_label', 'price', 'price_mode',
  'unit_label', 'min_qty', 'image', 'alt', 'gallery', 'short_description',
  'description', 'details', 'occasions', 'keywords', 'customiser', 'size_id',
  'featured', 'sort_order'
];

const rows = PRODUCTS.map((p) =>
  '  (' +
  [
    q(p.id),
    q(p.slug),
    q(p.name),
    q(p.category),
    q(p.categoryLabel || ''),
    Number(p.price),
    q(p.priceMode || 'fixed'),
    q(p.unitLabel || ''),
    p.minQty ? Number(p.minQty) : 'null',
    q(p.image || ''),
    q(p.alt || ''),
    jsonb(p.gallery),
    q(p.shortDescription || ''),
    q(p.description || ''),
    jsonb(p.details),
    jsonb(p.occasions),
    jsonb(p.keywords),
    q(p.customiser || null),
    q(p.sizeId || null),
    p.featured ? 'true' : 'false',
    Number(p.sortOrder) || 0
  ].join(', ') +
  ')'
);

/* Everything except id, which is what the conflict is on, and
   published, which the studio owns. */
const UPDATES = COLUMNS.filter((c) => c !== 'id')
  .map((c) => `${c} = excluded.${c}`)
  .join(', ');

lines.push(
  `insert into public.products (${COLUMNS.join(', ')}) values\n` +
    rows.join(',\n') +
    `\non conflict (id) do update set ${UPDATES};`
);

const known = PRODUCTS.map((p) => q(p.id)).join(', ');
lines.push(
  `update public.products set published = false where id not in (${known});`
);

// ------------------------------------------------------ price variants

for (const size of FRAME_SIZES) {
  /* The id the cart makes: product id, then the size id. */
  const frame = PRODUCTS.find((p) => p.customiser === 'frame');
  if (!frame) continue;
  lines.push(
    `insert into public.price_variants (id, kind, parent_product_id, label, price_paise, active) values (` +
      [q(`${frame.id}-${size.id}`), q('frame-size'), q(frame.id), q(size.label), paise(size.price), 'true'].join(', ') +
      `) on conflict (id) do update set price_paise = excluded.price_paise, label = excluded.label, active = true;`
  );
}

/* Every poster is sold at every size, and each design prices
   separately, so this is a row per poster per size - not one row like
   the frames above. Without them the server cannot price
   `poster-botanical-pair-poster-a4` and refuses the order. */
for (const poster of PRODUCTS.filter((p) => p.customiser === 'poster')) {
  for (const size of poster.posterSizes || POSTER_SIZES) {
    lines.push(
      `insert into public.price_variants (id, kind, parent_product_id, label, price_paise, active) values (` +
        [
          q(`${poster.id}-${size.id}`),
          q('poster-size'),
          q(poster.id),
          q(size.label),
          paise(size.price),
          'true'
        ].join(', ') +
        `) on conflict (id) do update set price_paise = excluded.price_paise, label = excluded.label, active = true;`
    );
  }
}

for (const box of BOX_VARIANTS) {
  lines.push(
    `insert into public.price_variants (id, kind, parent_product_id, label, price_paise, active) values (` +
      [
        q(box.id),
        q('hamper-box'),
        q('hamper-build-your-own'),
        q(`${box.label} — ${box.sizeLabel}`),
        paise(box.price),
        'true'
      ].join(', ') +
      `) on conflict (id) do update set price_paise = excluded.price_paise, label = excluded.label, active = true;`
  );
}

lines.push('commit;');

process.stdout.write(lines.join('\n') + '\n');
