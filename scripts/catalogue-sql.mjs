/* Turns the catalogue the site is built with into SQL.

   The server prices every order itself; it cannot take the browser's
   word for what a thing costs. That means the database needs the same
   catalogue the shop shows, and this writes the statements that put it
   there:

   - products: every row in src/data/products.js
   - price_variants: the things that are sold at a price but are not
     products in their own right - the three frame sizes, the twelve
     hamper boxes. The cart builds ids like
     `frame-couple-eye-frame-a4` for these, and the server has to be
     able to price one without trusting the number attached to it.

   Anything in the database that the catalogue no longer has is not
   deleted. It is marked unpublished, which takes it out of the shop and
   stops it being orderable while leaving the record alone.

   Run:  node --import ./tests/resolve-extensions.mjs scripts/catalogue-sql.mjs
   It prints SQL. It does not connect to anything.                    */

import { PRODUCTS, FRAME_SIZES } from '../src/data/products.js';
import { BOX_VARIANTS } from '../src/data/hamperKit.js';

const q = (v) =>
  v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;

/* Money is held as whole paise everywhere past the browser. */
const paise = (rupees) => Math.round(Number(rupees) * 100);

const lines = [];

lines.push('-- generated by scripts/catalogue-sql.mjs - do not edit by hand');
lines.push('begin;');

// ------------------------------------------------------------ products

/* Only the columns the server prices from. The shop's own copy of a
   product - its photographs, its description - is already in the
   bundle and is not what this is for. */
const rows = PRODUCTS.map((p) =>
  '  (' +
  [
    q(p.id),
    q(p.slug),
    q(p.name),
    q(p.category),
    q(p.categoryLabel || ''),
    Number(p.price),
    p.minQty ? Number(p.minQty) : 'null',
    q(p.customiser || null)
  ].join(', ') +
  ')'
);

lines.push(
  'insert into public.products (id, slug, name, category, category_label, price, min_qty, customiser) values\n' +
    rows.join(',\n') +
    '\non conflict (id) do update set name = excluded.name, slug = excluded.slug, ' +
    'category = excluded.category, category_label = excluded.category_label, ' +
    'price = excluded.price, min_qty = excluded.min_qty, ' +
    'customiser = excluded.customiser, published = true;'
);

const known = PRODUCTS.map((p) => q(p.id)).join(', ');
lines.push(
  `update public.products set published = false where id not in (${known});`
);

// ------------------------------------------------------ price variants

for (const size of FRAME_SIZES) {
  /* The id the cart makes: product id, then the size id. */
  const frame = PRODUCTS.find((p) => p.customiser === 'frame');
  if (!frame) continue;
  lines.push(
    `insert into public.price_variants (id, kind, parent_product_id, label, price_paise, active) values (` +
      [q(`${frame.id}-${size.id}`), q('frame-size'), q(frame.id), q(size.label), paise(size.price), 'true'].join(', ') +
      `) on conflict (id) do update set price_paise = excluded.price_paise, label = excluded.label, active = true;`
  );
}

for (const box of BOX_VARIANTS) {
  lines.push(
    `insert into public.price_variants (id, kind, parent_product_id, label, price_paise, active) values (` +
      [
        q(box.id),
        q('hamper-box'),
        q('hamper-build-your-own'),
        q(`${box.label} — ${box.sizeLabel}`),
        paise(box.price),
        'true'
      ].join(', ') +
      `) on conflict (id) do update set price_paise = excluded.price_paise, label = excluded.label, active = true;`
  );
}

lines.push('commit;');

process.stdout.write(lines.join('\n') + '\n');
